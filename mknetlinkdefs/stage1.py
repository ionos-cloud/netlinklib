"""
Generate temporary C programs that genrarate Python code for defs and sizes
of various objects in the kernel headers used for netlink operations.

Include build dependency on `linux-libc-dev` package

Generating two C programs is stage 1 of the process.

On stage 2, C programs are compiled and executed. One produces the final
result - Python "defs.py" with values of defines and enums, and the other
produces Python "sizes.py" to be used at stage 3.

Stage 3 parses headers "properly" and generates Python file with class
definition for structures.
"""

